import type { Exam } from './schema';
export type Answer = string[] | string;
export type Response = { answer: Answer; visited: boolean; review: boolean };
export type SectionResult = {
  id: string;
  title: string;
  marks: number;
  maximum: number;
  percentage: number;
  qualified: boolean;
  hasThreshold: boolean;
  correct: number;
  incorrect: number;
  unanswered: number;
  partial: number;
};
export type QuestionResult = {
  id: string;
  sectionId: string;
  marks: number;
  outcome: 'correct' | 'incorrect' | 'unanswered' | 'partial';
};
export type Result = {
  marks: number;
  maximum: number;
  percentage: number;
  passed: boolean;
  correct: number;
  incorrect: number;
  partial: number;
  attempted: number;
  unanswered: number;
  review: number;
  negativeMarks: number;
  accuracy: number;
  sections: SectionResult[];
  questions: QuestionResult[];
  elapsedSeconds: number;
  timeTaken: string;
};
export type Attempt = {
  id: string;
  examId: string;
  exam: Exam;
  candidate: string;
  startedAt: number;
  deadline: number;
  completedAt?: number;
  status: 'active' | 'completed';
  reason?: 'manual' | 'timeout' | 'sections-expired';
  currentSection: number;
  currentQuestion: number;
  sectionStartedAt: Record<string, number>;
  lockedSections: string[];
  responses: Record<string, Response>;
  revision: number;
  result?: Result;
};
export type ExamRecord = { id: string; exam: Exam; importedAt: number; updatedAt: number };
